import assert from "node:assert/strict";
import {createServer} from "vite";
import react from "@vitejs/plugin-react";
import React from "react";
import {renderToStaticMarkup} from "react-dom/server";
const server=await createServer({configFile:false,plugins:[react()],optimizeDeps:{noDiscovery:true,include:[]},server:{middlewareMode:true,hmr:false},appType:"custom"});
try {
  const {default:Scope}=await server.ssrLoadModule("/src/ScopeConfirmation.jsx");
  const scope=renderToStaticMarkup(React.createElement(Scope));
  assert.match(scope,/<dialog[^>]*aria-labelledby=/);
  assert(!/<dialog[^>]*\sopen(?:\s|>)/.test(scope));
  assert(scope.includes("暂不确认"));
  const {default:Answers}=await server.ssrLoadModule("/src/QuestionAnswers.jsx");
  const answers=renderToStaticMarkup(React.createElement(Answers));
  assert(answers.includes("回答业务问题"));assert(answers.includes("保存本项回答"));
  const {default:Review}=await server.ssrLoadModule("/src/AnswerReview.jsx");
  const review=renderToStaticMarkup(React.createElement(Review,{answers:{answersDigest:"fixture",submission:{requestId:"fixture"}}}));
  assert(review.includes("继续核对"));assert(review.includes("只分析，不制作原型"));
  assert(!/<dialog[^>]*\sopen(?:\s|>)/.test(review));
  const {default:Decisions}=await server.ssrLoadModule("/src/BusinessDecisions.jsx");
  const decisions=renderToStaticMarkup(React.createElement(Decisions,{answers:{answersDigest:"fixture"}}));
  assert(decisions.includes("确认业务方案"));
  const {default:Implementation}=await server.ssrLoadModule("/src/Implementation.jsx");
  const implementation=renderToStaticMarkup(React.createElement(Implementation));
  assert(implementation.includes("查看制作准备"));assert(implementation.includes("暂不授权"));
  assert.match(implementation,/<button[^>]*disabled=""[^>]*>授权并开始制作原型/);
  assert(!/<dialog[^>]*\sopen(?:\s|>)/.test(implementation));
  const history=renderToStaticMarkup(React.createElement(Review,{answers:{answersDigest:"fixture"},historyOnly:true}));
  assert(!history.includes(">继续核对</button>"));assert(history.includes("不要求你再次确认"));
  assert(!/<dialog[^>]*\sopen(?:\s|>)/.test(decisions));
  assert(!/<dialog[^>]*\sopen(?:\s|>)/.test(answers));
  assert.match(answers,/<button[^>]*disabled=""[^>]*>保存本项回答/);
  const {default:Detail}=await server.ssrLoadModule("/src/ReadOnlyRequirement.jsx");
  const {sourceRequirements}=await server.ssrLoadModule("/src/source-requirements.js");
  const record={...sourceRequirements[0],id:"CR-029"};
  const detail=renderToStaticMarkup(React.createElement(Detail,{record}));
  assert.match(detail,/<header class="requirement-heading">[\s\S]*?requirement-heading-actions[\s\S]*?<\/header>/);
  assert(detail.indexOf("requirement-top-notices")<detail.indexOf("requirement-workspace"));
  const completedDetail=renderToStaticMarkup(React.createElement(Detail,{record:{...record,executionState:"completed",confirmedAt:"2026-09-12"}}));
  for(const label of ["预览原型","查看页面说明","查看原型交付清单","工程化原型已完成"])assert(completedDetail.includes(label));
  const other=renderToStaticMarkup(React.createElement(Detail,{record:sourceRequirements.find(x=>x.waiting)}));
  assert(other.indexOf("当前需要你")<other.indexOf("requirement-workspace"));
  console.log("PASS: header action slot, top notices, read-only pending prompt and closed accessible confirmation dialog");
} finally {await server.close();}
